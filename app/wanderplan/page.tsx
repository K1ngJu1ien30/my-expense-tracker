"use client";

import { useState, useMemo } from "react";
import { Plus, Trash2, Play, CheckCircle2, MapPin, Calendar, Edit3, Share2, Copy } from "lucide-react";
import { motion, AnimatePresence } from "framer-motion";
import { useAppContext } from "@/lib/context";
import { format, differenceInDays, isWithinInterval, parseISO } from "date-fns";
import { WP_CURRENCIES } from "@/lib/wanderplanConstants";
import CustomDatePicker from "@/components/CustomDatePicker";
import TodayTimeline from "@/components/wanderplan/TodayTimeline";
import TripCountdown from "@/components/wanderplan/TripCountdown";
import DailySpendingMeter from "@/components/wanderplan/DailySpendingMeter";

export default function WanderPlanDashboard() {
  const {
    accentColor, wpTrips, wpActivities, wpAllocations, wpExpenses,
    wpActiveTripId, createWPTrip, updateWPTrip, deleteWPTrip, setWPTripStatus,
    getWPTripDays, wpPlaces, wpPackingItems,
    confirmAction, triggerToast,
  } = useAppContext();

  const [showCreate, setShowCreate] = useState(false);
  const [name, setName] = useState("");
  const [destination, setDestination] = useState("");
  const [startDate, setStartDate] = useState(format(new Date(), "yyyy-MM-dd"));
  const [endDate, setEndDate] = useState(format(new Date(), "yyyy-MM-dd"));
  const [currencyCode, setCurrencyCode] = useState(WP_CURRENCIES[0].code);

  // Edit trip state
  const [editTrip, setEditTrip] = useState<string | null>(null);
  const [editName, setEditName] = useState("");
  const [editDest, setEditDest] = useState("");
  const [editStart, setEditStart] = useState("");
  const [editEnd, setEditEnd] = useState("");

  // Share trip state
  const [shareTrip, setShareTrip] = useState<string | null>(null);

  const activeTrip = useMemo(
    () => wpTrips.find(t => t.id === wpActiveTripId) || wpTrips.find(t => t.status === "active"),
    [wpTrips, wpActiveTripId]
  );

  // Upcoming trips sorted by start date
  const upcomingTrips = useMemo(
    () => wpTrips
      .filter(t => t.status === "planning")
      .sort((a, b) => a.start_date.localeCompare(b.start_date)),
    [wpTrips]
  );

  const handleCreate = async () => {
    if (!name.trim() || !destination.trim()) return;
    const result = await createWPTrip({
      name: name.trim(),
      destination: destination.trim(),
      start_date: startDate,
      end_date: endDate,
      currency_code: currencyCode,
      status: "planning",
      settings: {},
    } as never);
    if (result) {
      setShowCreate(false);
      setName(""); setDestination("");
      triggerToast("Trip created!");
    } else {
      triggerToast("Failed to create trip. Try again.");
    }
  };

  const handleDelete = (id: string, tripName: string) => {
    confirmAction("Delete Trip", `Delete "${tripName}" and all its data?`, () => deleteWPTrip(id));
  };

  const openEdit = (trip: typeof wpTrips[0]) => {
    setEditTrip(trip.id);
    setEditName(trip.name);
    setEditDest(trip.destination);
    setEditStart(trip.start_date);
    setEditEnd(trip.end_date);
  };

  const handleSaveEdit = async () => {
    if (!editTrip || !editName.trim() || !editDest.trim()) return;
    await updateWPTrip(editTrip, { name: editName.trim(), destination: editDest.trim(), start_date: editStart, end_date: editEnd } as never);
    setEditTrip(null);
    triggerToast("Trip updated!");
  };

  const generateTripSummary = (tripId: string) => {
    const trip = wpTrips.find(t => t.id === tripId);
    if (!trip) return;
    const days = getWPTripDays(trip.id);
    const acts = wpActivities.filter(a => days.some(d => d.id === a.trip_day_id));
    const places = wpPlaces.filter(p => p.trip_id === trip.id);
    const packing = wpPackingItems.filter(i => i.trip_id === trip.id);
    const totalBudget = wpAllocations.filter(a => a.trip_id === trip.id).reduce((s, a) => s + a.allocated_cents, 0);
    const totalSpent = wpExpenses.filter(e => e.trip_id === trip.id).reduce((s, e) => s + e.amount_cents, 0);
    const daysCount = differenceInDays(parseISO(trip.end_date), parseISO(trip.start_date)) + 1;

    const lines = [
      `✈️ ${trip.name}`,
      `📍 ${trip.destination}`,
      `📅 ${format(parseISO(trip.start_date), "MMM d")} — ${format(parseISO(trip.end_date), "MMM d, yyyy")} (${daysCount} days)`,
      ``,
      `📊 Stats:`,
      `  ${acts.length} activities planned`,
      `  ${places.length} places saved`,
      totalBudget > 0 ? `  💰 Budget: ${trip.currency_code} ${(totalBudget / 100).toFixed(0)} | Spent: ${trip.currency_code} ${(totalSpent / 100).toFixed(0)}` : "",
      packing.length > 0 ? `  🎒 ${packing.filter(i => i.is_packed).length}/${packing.length} packed` : "",
      ``,
      `— Generated by Expense Tracker Pro`,
    ].filter(Boolean).join("\n");

    if (navigator.clipboard) {
      navigator.clipboard.writeText(lines).then(() => triggerToast("Trip summary copied!"));
    }
    setShareTrip(null);
  };

  return (
    <div className="p-6 space-y-4 animate-in fade-in duration-500">
      {/* Active Trip Summary */}
      {activeTrip && (
        <div className="bg-gradient-to-br from-sky-500 to-blue-600 rounded-3xl p-5 text-white shadow-heavy">
          <div className="flex items-start justify-between">
            <div>
              <p className="text-xs font-bold uppercase tracking-wider text-white/70">Active Trip</p>
              <h2 className="text-2xl font-black mt-1">{activeTrip.name}</h2>
              <div className="flex items-center gap-1.5 mt-1 text-white/80">
                <MapPin className="w-3.5 h-3.5" />
                <span className="text-sm font-medium">{activeTrip.destination}</span>
              </div>
            </div>
            <button onClick={() => setWPTripStatus(activeTrip.id, "completed")} className="bg-white/20 backdrop-blur-sm px-3 py-1.5 rounded-full text-xs font-bold flex items-center gap-1.5 active:scale-95 transition-transform">
              <CheckCircle2 className="w-3.5 h-3.5" /> Complete
            </button>
          </div>

          <div className="grid grid-cols-3 gap-3 mt-4">
            {(() => {
              const days = getWPTripDays(activeTrip.id);
              const acts = wpActivities.filter(a => days.some(d => d.id === a.trip_day_id));
              const totalBudget = wpAllocations.filter(a => a.trip_id === activeTrip.id).reduce((s, a) => s + a.allocated_cents, 0);
              const totalSpent = wpExpenses.filter(e => e.trip_id === activeTrip.id).reduce((s, e) => s + e.amount_cents, 0);
              return (
                <>
                  <div className="bg-white/10 rounded-2xl p-3 text-center">
                    <p className="text-2xl font-black">{days.length}</p>
                    <p className="text-[10px] font-bold text-white/70 uppercase">Days</p>
                  </div>
                  <div className="bg-white/10 rounded-2xl p-3 text-center">
                    <p className="text-2xl font-black">{acts.length}</p>
                    <p className="text-[10px] font-bold text-white/70 uppercase">Activities</p>
                  </div>
                  <div className="bg-white/10 rounded-2xl p-3 text-center">
                    <p className="text-lg font-black">{((totalBudget - totalSpent) / 100).toFixed(0)}</p>
                    <p className="text-[10px] font-bold text-white/70 uppercase">Remaining</p>
                  </div>
                </>
              );
            })()}
          </div>

          {/* Trip progress bar */}
          <div className="mt-3">
            <TripCountdown trip={activeTrip} />
          </div>
        </div>
      )}

      {/* Daily spending meter (active trip) */}
      {activeTrip?.status === "active" && <DailySpendingMeter trip={activeTrip} />}

      {/* Today Timeline for active trip */}
      {activeTrip?.status === "active" && <TodayTimeline trip={activeTrip} />}

      {/* Upcoming trip countdowns */}
      {upcomingTrips.length > 0 && (
        <div className="space-y-2">
          <p className="text-xs font-bold uppercase tracking-wider text-muted-foreground">Upcoming</p>
          {upcomingTrips.map(t => (
            <div key={t.id} className="bg-card rounded-2xl shadow-soft border border-border/40 p-3">
              <div className="flex items-center gap-2 mb-2">
                <span className="text-sm">✈️</span>
                <span className="font-bold text-sm text-foreground">{t.name}</span>
                <span className="text-[10px] text-muted-foreground font-medium ml-auto">{t.destination}</span>
              </div>
              <TripCountdown trip={t} />
            </div>
          ))}
        </div>
      )}

      {/* Create Trip Button */}
      <button
        onClick={() => setShowCreate(true)}
        style={{ backgroundColor: accentColor, boxShadow: `0 4px 20px ${accentColor}40` }}
        className="w-full py-4 rounded-2xl text-white font-bold text-sm flex items-center justify-center gap-2 active:scale-[0.97] transition-all"
      >
        <Plus className="w-5 h-5" /> New Trip
      </button>

      {/* Trip List */}
      <div className="space-y-3">
        {wpTrips.map(trip => {
          const isActive = trip.status === "active";
          const isCompleted = trip.status === "completed";
          const initials = trip.destination.split(" ").map(w => w[0]).join("").slice(0, 2).toUpperCase();
          const daysCount = differenceInDays(parseISO(trip.end_date), parseISO(trip.start_date)) + 1;
          const isOngoing = trip.status === "active" && (() => {
            try { return isWithinInterval(new Date(), { start: parseISO(trip.start_date), end: parseISO(trip.end_date) }); } catch { return false; }
          })();

          return (
            <div key={trip.id} className="bg-card rounded-3xl shadow-soft border border-border/40 overflow-hidden">
              <div className={`h-20 flex items-center justify-center ${isActive ? "bg-gradient-to-br from-sky-500 to-blue-600" : isCompleted ? "bg-gradient-to-br from-emerald-500 to-green-600" : "bg-gradient-to-br from-slate-400 to-slate-500"}`}>
                <span className="text-3xl font-black text-white/80">{initials}</span>
              </div>
              <div className="p-4 space-y-2">
                <div className="flex items-start justify-between">
                  <div>
                    <h3 className="font-bold text-foreground">{trip.name}</h3>
                    <div className="flex items-center gap-1.5 mt-0.5">
                      <MapPin className="w-3 h-3 text-muted-foreground" />
                      <span className="text-xs text-muted-foreground font-medium">{trip.destination}</span>
                    </div>
                  </div>
                  <span className={`text-[10px] font-bold px-2 py-0.5 rounded-full uppercase tracking-wider ${isActive ? "bg-sky-500/10 text-sky-500" : isCompleted ? "bg-emerald-500/10 text-emerald-500" : "bg-muted text-muted-foreground"}`}>
                    {isOngoing ? "On Trip" : trip.status}
                  </span>
                </div>

                <div className="flex items-center gap-2 text-xs text-muted-foreground font-medium">
                  <Calendar className="w-3 h-3" />
                  {format(parseISO(trip.start_date), "MMM d")} — {format(parseISO(trip.end_date), "MMM d, yyyy")} · {daysCount} days
                </div>

                <div className="flex gap-2 pt-1">
                  {trip.status === "planning" && (
                    <button onClick={() => setWPTripStatus(trip.id, "active")} className="flex-1 py-2 rounded-xl text-xs font-bold flex items-center justify-center gap-1.5 active:scale-95 transition-transform" style={{ backgroundColor: `${accentColor}1A`, color: accentColor }}>
                      <Play className="w-3.5 h-3.5" /> Start Trip
                    </button>
                  )}
                  <button onClick={() => openEdit(trip)} className="p-2 rounded-xl bg-muted text-muted-foreground hover:text-foreground active:scale-95 transition-all">
                    <Edit3 className="w-4 h-4" />
                  </button>
                  <button onClick={() => { setShareTrip(trip.id); generateTripSummary(trip.id); }} className="p-2 rounded-xl bg-sky-500/10 text-sky-500 active:scale-95 transition-transform">
                    <Copy className="w-4 h-4" />
                  </button>
                  <button onClick={() => handleDelete(trip.id, trip.name)} className="p-2 rounded-xl bg-red-500/10 text-red-500 active:scale-95 transition-transform">
                    <Trash2 className="w-4 h-4" />
                  </button>
                </div>
              </div>
            </div>
          );
        })}

        {wpTrips.length === 0 && (
          <div className="text-center py-12 space-y-2">
            <p className="text-4xl">✈️</p>
            <p className="font-bold text-foreground">No trips yet</p>
            <p className="text-xs text-muted-foreground font-medium">Create your first trip to start planning!</p>
          </div>
        )}
      </div>

      {/* Create Trip Modal */}
      <AnimatePresence>
        {showCreate && (
          <div className="fixed inset-0 z-[200] flex items-end justify-center">
            <motion.div initial={{ opacity: 0 }} animate={{ opacity: 1 }} exit={{ opacity: 0 }} onClick={() => setShowCreate(false)} className="absolute inset-0 bg-black/40 backdrop-blur-sm" />
            <motion.div
              initial={{ y: "100%" }} animate={{ y: 0 }} exit={{ y: "100%" }}
              transition={{ type: "spring", damping: 28, stiffness: 300 }}
              className="relative w-full max-w-md bg-card rounded-t-[2rem] border-t border-border/50 shadow-heavy p-6 space-y-4 pb-safe"
            >
              <div className="w-10 h-1 bg-muted rounded-full mx-auto" />
              <h2 className="text-lg font-bold text-foreground">New Trip</h2>

              <input value={name} onChange={e => setName(e.target.value)} placeholder="Trip name" className="w-full bg-muted/60 rounded-xl px-4 py-3 text-sm font-semibold outline-none border border-border text-foreground placeholder:text-muted-foreground" />
              <input value={destination} onChange={e => setDestination(e.target.value)} placeholder="Destination" className="w-full bg-muted/60 rounded-xl px-4 py-3 text-sm font-semibold outline-none border border-border text-foreground placeholder:text-muted-foreground" />

              <div className="grid grid-cols-2 gap-3">
                <div>
                  <p className="text-xs font-bold text-muted-foreground mb-1">Start</p>
                  <CustomDatePicker value={startDate} onChange={setStartDate} accentColor={accentColor} />
                </div>
                <div>
                  <p className="text-xs font-bold text-muted-foreground mb-1">End</p>
                  <CustomDatePicker value={endDate} onChange={setEndDate} accentColor={accentColor} />
                </div>
              </div>

              <div>
                <p className="text-xs font-bold text-muted-foreground mb-1.5">Currency</p>
                <div className="flex gap-2 overflow-x-auto hide-scrollbar pb-1">
                  {WP_CURRENCIES.map(c => (
                    <button
                      key={c.code}
                      type="button"
                      onClick={() => setCurrencyCode(c.code)}
                      className="whitespace-nowrap px-4 py-2 rounded-full text-sm font-bold transition-all shrink-0"
                      style={currencyCode === c.code
                        ? { backgroundColor: accentColor, color: "#fff" }
                        : { backgroundColor: "var(--color-muted)", color: "var(--color-muted-foreground)" }
                      }
                    >
                      {c.code}
                    </button>
                  ))}
                </div>
              </div>

              <button onClick={handleCreate} disabled={!name.trim() || !destination.trim()} style={{ backgroundColor: accentColor }} className="w-full py-4 rounded-2xl text-white font-bold text-sm active:scale-[0.97] transition-all disabled:opacity-40">
                Create Trip
              </button>
            </motion.div>
          </div>
        )}
      </AnimatePresence>

      {/* Edit Trip Modal */}
      <AnimatePresence>
        {editTrip && (
          <div className="fixed inset-0 z-[200] flex items-center justify-center p-4">
            <motion.div initial={{ opacity: 0 }} animate={{ opacity: 1 }} exit={{ opacity: 0 }} onClick={() => setEditTrip(null)} className="absolute inset-0 bg-black/40 backdrop-blur-sm" />
            <motion.div initial={{ scale: 0.95, opacity: 0 }} animate={{ scale: 1, opacity: 1 }} exit={{ scale: 0.95, opacity: 0 }} className="relative w-full max-w-sm bg-card rounded-3xl p-6 shadow-heavy space-y-4 border border-border/50">
              <h3 className="font-bold text-foreground text-lg">Edit Trip</h3>
              <input value={editName} onChange={e => setEditName(e.target.value)} placeholder="Trip name" className="w-full bg-muted/60 rounded-xl px-4 py-3 text-sm font-semibold outline-none border border-border text-foreground placeholder:text-muted-foreground" />
              <input value={editDest} onChange={e => setEditDest(e.target.value)} placeholder="Destination" className="w-full bg-muted/60 rounded-xl px-4 py-3 text-sm font-semibold outline-none border border-border text-foreground placeholder:text-muted-foreground" />
              <div className="grid grid-cols-2 gap-3">
                <div>
                  <p className="text-xs font-bold text-muted-foreground mb-1">Start</p>
                  <CustomDatePicker value={editStart} onChange={setEditStart} accentColor={accentColor} />
                </div>
                <div>
                  <p className="text-xs font-bold text-muted-foreground mb-1">End</p>
                  <CustomDatePicker value={editEnd} onChange={setEditEnd} accentColor={accentColor} />
                </div>
              </div>
              <button onClick={handleSaveEdit} disabled={!editName.trim() || !editDest.trim()} style={{ backgroundColor: accentColor }} className="w-full py-3 rounded-2xl text-white font-bold text-sm active:scale-[0.97] transition-all disabled:opacity-40">
                Save Changes
              </button>
            </motion.div>
          </div>
        )}
      </AnimatePresence>
    </div>
  );
}
